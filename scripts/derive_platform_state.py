#!/usr/bin/env python3
# Implements: architecture/reference/platform-component-registry.yaml §institutional_state
# Constitutional basis: C-008, C-032, C-059, C-071
"""Derive platform-state facts from the repository tree and the Git-built delivery ledger.

Facts that can be counted (Work Contracts, ADRs, claims, catalogued CCTs, merged pull requests) are
never typed by hand. The tree supplies everything except merged-PR evidence, which Git supplies and
`--refresh-ledger` records in `architecture/reference/work-contract-delivery-ledger.yaml`, so checks
stay deterministic in shallow or offline environments.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
LEDGER = Path("architecture/reference/work-contract-delivery-ledger.yaml")
LEDGER_HEADER = (
    "# Merged pull requests on the authoritative branch, newest first. Generated by\n"
    "# scripts/derive_platform_state.py --refresh-ledger; never edit by hand.\n"
    "# `wc` lists Work Contract references found in the PR's commits and branch name.\n"
)
WC_FILE = re.compile(r"^WC-(\d{3,})-.+\.md$")
WC_REFERENCE = re.compile(r"\bWC-?(\d{3})\b")
PR_MERGE = re.compile(r"^Merge pull request #(\d+) from (\S+)")
PR_SQUASH = re.compile(r"\(#(\d+)\)\s*$")
CCT_DECLARATION = re.compile(r"(?:^\*\*|^## |^\| `)(CCT-[A-Z0-9]+(?:-[A-Z0-9]+)*)", re.MULTILINE)
TITLE = re.compile(r"^#\s+(?:WC-|Work Contract\s+)(\d{3,})\s*[-–—:]?\s*(.*)$")
STATUS_ROW = re.compile(
    r"^(?:\|\s*Status\s*\|\s*(.+?)\s*\|\s*|\*\*Status:\*\*\s*(.+?)\s*|[-*]\s*Status:\s*(.+?)\s*)$",
    re.MULTILINE | re.IGNORECASE,
)
MAXIMUM_STATUS_LENGTH = 120


def work_contracts(root: Path) -> dict[int, dict[str, str]]:
    """One record per Work Contract id, choosing the file whose heading names that id."""
    by_id: dict[int, list[Path]] = {}
    for path in sorted((root / "work-contracts").glob("WC-*.md")):
        match = WC_FILE.match(path.name)
        if match:
            by_id.setdefault(int(match.group(1)), []).append(path)
    records: dict[int, dict[str, str]] = {}
    for number, paths in by_id.items():
        chosen, title = paths[0], ""
        for path in paths:
            first_line = path.read_text(encoding="utf-8").split("\n", 1)[0]
            heading = TITLE.match(first_line)
            if heading and int(heading.group(1)) == number and heading.group(2).strip():
                chosen, title = path, heading.group(2).strip()
                break
        text = chosen.read_text(encoding="utf-8")
        status_match = STATUS_ROW.search(text)
        status = next((group for group in status_match.groups() if group), "UNRECORDED") if status_match else "UNRECORDED"
        status = re.split(r"(?<=[A-Za-z0-9)])\.\s", status, maxsplit=1)[0]
        records[number] = {
            "id": f"WC-{number:03d}",
            "title": title or chosen.stem,
            "status": status[:MAXIMUM_STATUS_LENGTH].rstrip(),
            "file": chosen.name,
        }
    return records


def adr_count(root: Path) -> int:
    ids = {match.group(1) for path in (root / "adr").glob("ADR-*.md") if (match := re.match(r"^(ADR-\d+)", path.name))}
    return len(ids)


def claim_inventory(root: Path) -> dict[str, Any]:
    """Claims count as ratified unless their Status line says otherwise; absent numbers are gaps."""
    ratified: set[int] = set()
    numbers: set[int] = set()
    for path in (root / "knowledge/claims").glob("C-[0-9][0-9][0-9].md"):
        number = int(path.stem[2:])
        numbers.add(number)
        status = re.search(r"^Status:\s+(\S+)", path.read_text(encoding="utf-8"), re.MULTILINE)
        if not status or status.group(1) == "RATIFIED":
            ratified.add(number)
    gaps = [f"C-{n:03d}" for n in range(min(numbers), max(numbers) + 1) if n not in ratified] if numbers else []
    return {"ratified": len(ratified), "gaps": gaps}


def catalogued_ccts(root: Path) -> int:
    text = (root / "tests/constitutional/README.md").read_text(encoding="utf-8")
    return len(set(CCT_DECLARATION.findall(text)))


def load_ledger(root: Path) -> list[dict[str, Any]]:
    path = root / LEDGER
    if not path.is_file():
        return []
    loaded = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    entries = loaded.get("merged_pull_requests", [])
    if not isinstance(entries, list):
        raise ValueError(f"{LEDGER} merged_pull_requests must be a list")
    return entries


def render_ledger(entries: list[dict[str, Any]]) -> str:
    lines = [LEDGER_HEADER, "merged_pull_requests:"]
    for entry in entries:
        work = "[" + ", ".join(entry["wc"]) + "]"
        lines.append(f'  - {{pr: {entry["pr"]}, merge: {entry["merge"]}, date: "{entry["date"]}", wc: {work}}}')
    return "\n".join(lines) + "\n"


def git(root: Path, *arguments: str) -> str:
    result = subprocess.run(  # noqa: S603
        ["git", *arguments],  # noqa: S607
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise ValueError(f"git {' '.join(arguments)} failed: {result.stderr.strip()}")
    return result.stdout


def work_contract_references(text: str) -> list[str]:
    return sorted({f"WC-{int(number):03d}" for number in WC_REFERENCE.findall(text)})


def merged_pull_requests(root: Path, ref: str) -> list[dict[str, Any]]:
    """Pull requests on the first-parent history of ref, newest first, with Work Contract references."""
    log = git(root, "log", ref, "--first-parent", "--format=%H%x00%P%x00%cs%x00%s%x1e")
    entries: dict[int, dict[str, Any]] = {}
    for record in log.split("\x1e"):
        fields = record.strip("\n").split("\x00")
        if len(fields) != 4:
            continue
        sha, parents, date, subject = fields
        merged = PR_MERGE.match(subject)
        squashed = PR_SQUASH.search(subject)
        if merged:
            number = int(merged.group(1))
            first, second = parents.split()[:2]
            context = [subject, merged.group(2), git(root, "log", f"{first}..{second}", "--format=%s%n%b")]
        elif squashed and len(parents.split()) == 1:
            number = int(squashed.group(1))
            context = [subject, git(root, "show", "-s", "--format=%b", sha)]
        else:
            continue
        if number in entries:
            continue
        entries[number] = {
            "pr": number,
            "merge": sha[:10],
            "date": date,
            "wc": work_contract_references("\n".join(context)),
        }
    return list(entries.values())


def derive(root: Path = REPO_ROOT) -> dict[str, Any]:
    contracts = work_contracts(root)
    ledger = load_ledger(root)
    delivered: dict[int, list[dict[str, Any]]] = {}
    for entry in ledger:
        for reference in entry["wc"]:
            delivered.setdefault(int(reference[3:]), []).append(entry)
    recorded = len(contracts)
    with_evidence = sum(1 for number in contracts if number in delivered)
    latest_delivery = next((entry for entry in ledger if entry["wc"]), None)
    latest_contract = max(contracts) if contracts else None
    implementation = None
    if latest_delivery:
        number = max(int(reference[3:]) for reference in latest_delivery["wc"])
        implementation = {
            "work_contract": f"WC-{number:03d}",
            "title": contracts.get(number, {}).get("title", "title unrecorded"),
            "evidence": f"PR #{latest_delivery['pr']} merged as {latest_delivery['merge']}",
        }
    return {
        "version": (root / "VERSION").read_text(encoding="utf-8").strip(),
        "as_of": max((entry["date"] for entry in ledger), default="unrecorded"),
        "release_date": latest_delivery["date"] if latest_delivery else "unrecorded",
        "latest_completed_implementation": implementation,
        "latest_recorded_contract": contracts.get(latest_contract) if latest_contract else None,
        "work_contracts": contracts,
        "delivered": delivered,
        "counts": {
            "recorded": recorded,
            "with_merged_pr_evidence": with_evidence,
            "without_merged_pr_evidence": recorded - with_evidence,
            "adrs": adr_count(root),
            "claims": claim_inventory(root),
            "ccts_catalogued": catalogued_ccts(root),
        },
    }


def refresh_ledger(root: Path, ref: str) -> bool:
    rendered = render_ledger(merged_pull_requests(root, ref))
    path = root / LEDGER
    if path.is_file() and path.read_text(encoding="utf-8") == rendered:
        return False
    path.write_text(rendered, encoding="utf-8")
    return True


def ledger_gaps(root: Path, ref: str) -> list[str]:
    """Pull-request numbers merged on ref that the committed ledger does not record."""
    recorded = {entry["pr"] for entry in load_ledger(root)}
    return [f"#{entry['pr']}" for entry in merged_pull_requests(root, ref) if entry["pr"] not in recorded]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-ledger", action="store_true", help="rebuild the delivery ledger from Git history")
    parser.add_argument("--check-ledger", action="store_true", help="fail when the ledger lacks merged PRs on --ref")
    parser.add_argument("--ref", default="origin/main", help="authoritative branch for the ledger")
    args = parser.parse_args()
    if args.refresh_ledger:
        print(f"{'updated' if refresh_ledger(REPO_ROOT, args.ref) else 'unchanged'} {LEDGER}")
        return 0
    if args.check_ledger:
        missing = ledger_gaps(REPO_ROOT, args.ref)
        if missing:
            print(f"{LEDGER} lacks merged pull requests: {', '.join(missing)}", file=sys.stderr)
            return 1
        return 0
    state = derive()
    print(yaml.safe_dump({key: state[key] for key in ("version", "as_of", "counts")}, sort_keys=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
