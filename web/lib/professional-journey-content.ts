import type { SupportedLocale } from './preferences';
import { supportedLocales } from './preferences';

export type JourneyStageId = 'opening' | 'business' | 'goals' | 'agreement' | 'ready' | 'working';
export type JourneyRailId = 'business' | 'goals' | 'ways-of-working' | 'working';
export type ProfessionalStoryId = 'agricultural-advisor' | 'digital-marketing-professional';

export type JourneyStage = Readonly<{
  id: JourneyStageId;
  railId: JourneyRailId;
  title: string;
  summary: string;
  details: readonly string[];
}>;

export type ProfessionalJourneyStory = Readonly<{
  id: ProfessionalStoryId;
  selectorLabel: string;
  contextLabel: string;
  illustrationLabel: string;
  stages: readonly [JourneyStage, JourneyStage, JourneyStage, JourneyStage, JourneyStage, JourneyStage];
}>;

export type ProfessionalJourneyContent = Readonly<{
  heroTitle: string;
  heroSubtitle: string;
  finalMessage: string;
  accessibleSummary: string;
  railLabels: Readonly<Record<JourneyRailId, string>>;
  stories: readonly [ProfessionalJourneyStory, ProfessionalJourneyStory];
}>;

const STAGE_ORDER: readonly Readonly<{ id: JourneyStageId; railId: JourneyRailId }>[] = [
  { id: 'opening', railId: 'business' },
  { id: 'business', railId: 'business' },
  { id: 'goals', railId: 'goals' },
  { id: 'agreement', railId: 'ways-of-working' },
  { id: 'ready', railId: 'ways-of-working' },
  { id: 'working', railId: 'working' },
];

type StageCopy = Readonly<{ title: string; summary: string; details: readonly string[] }>;

type LocaleCopy = Readonly<{
  heroTitle: string;
  heroSubtitle: string;
  finalMessage: string;
  accessibleSummary: string;
  railLabels: Readonly<Record<JourneyRailId, string>>;
  agri: Readonly<{ selectorLabel: string; contextLabel: string; illustrationLabel: string; stages: readonly [StageCopy, StageCopy, StageCopy, StageCopy, StageCopy, StageCopy] }>;
  dma: Readonly<{ selectorLabel: string; contextLabel: string; illustrationLabel: string; stages: readonly [StageCopy, StageCopy, StageCopy, StageCopy, StageCopy, StageCopy] }>;
}>;

function buildStage(index: number, copy: StageCopy): JourneyStage {
  return { id: STAGE_ORDER[index].id, railId: STAGE_ORDER[index].railId, title: copy.title, summary: copy.summary, details: copy.details };
}

function buildStory(id: ProfessionalStoryId, story: LocaleCopy['agri'] | LocaleCopy['dma']): ProfessionalJourneyStory {
  const [stage0, stage1, stage2, stage3, stage4, stage5] = story.stages;
  const stages: ProfessionalJourneyStory['stages'] = [
    buildStage(0, stage0), buildStage(1, stage1), buildStage(2, stage2),
    buildStage(3, stage3), buildStage(4, stage4), buildStage(5, stage5),
  ];
  return { id, selectorLabel: story.selectorLabel, contextLabel: story.contextLabel, illustrationLabel: story.illustrationLabel, stages };
}


function buildContent(copy: LocaleCopy): ProfessionalJourneyContent {
  return {
    heroTitle: copy.heroTitle,
    heroSubtitle: copy.heroSubtitle,
    finalMessage: copy.finalMessage,
    accessibleSummary: copy.accessibleSummary,
    railLabels: copy.railLabels,
    stories: [buildStory('agricultural-advisor', copy.agri), buildStory('digital-marketing-professional', copy.dma)],
  };
}

